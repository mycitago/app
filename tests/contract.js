ok(A.includes('navigator.clipboard'),'falta fallback copiar');
ok(S.includes('service.image_url || serviceFallbackImage'),'servicio sin imagen real/fallback');
ok(C.includes('grid-template-columns:minmax(220px,260px) minmax(0,1fr) minmax(220px,260px)'),'grid desktop incorrecto');
ok(C.includes('@media(max-width:980px)'),'falta responsive');
ok(C.includes('.desktop-gallery-rail[hidden]'),'galería no se oculta si no hay datos');
ok(R.includes('fetchVerifiedPublicReviews'),'helper reseñas no existe');
process.exit(bad?1:0);
